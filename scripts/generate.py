#!/usr/bin/env python3
"""Generate the website catalog, documentation gallery, and packaged QML helpers."""
import argparse
import json
from pathlib import Path
import shutil
import sys

REPO = Path(__file__).resolve().parents[1]


def outputs():
    data = json.loads((REPO / "theme-catalog.json").read_text())
    themes = data["themes"]
    result = {REPO / "website/catalog.js": "// Generated by scripts/generate.py; edit theme-catalog.json.\nwindow.THEME_CATALOG = " + json.dumps(themes, indent=2) + ";\n"}
    gallery = "<!-- Generated by scripts/generate.py; edit theme-catalog.json. -->\n\n# Theme gallery\n\n| Theme | Preview |\n| --- | --- |\n"
    for theme in themes:
        gallery += f"| `{theme['id']}` | ![Preview](../themes/{theme['id']}/{theme['thumbnail']}) |\n"
        for component in (REPO / "common").glob("*.qml"):
            result[REPO / "themes" / theme["id"] / "components" / component.name] = component.read_text()
    result[REPO / "docs/GALLERY.md"] = gallery
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                stale.append(str(path.relative_to(REPO)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("Generated files are stale; run python3 scripts/generate.py:\n" + "\n".join(stale), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
